// Static site rendering, ported from internal/site (Go). Same output
// shapes: one HTML document per page naming the exact head revision in
// its footer, one index, and webmcp.js generated from the shared tool
// definitions — here imported from the canonical
// tools.definitions.json at the repo root, the same file the Go
// runtime's definitions are checked against in CI, so the browser and
// non-browser agent surfaces can never drift.
//
// Known divergence (M3 scope spec §5): the Go build renders Markdown
// with goldmark and this runtime with marked. The HTML differs in
// details; conformance compares rendered content and the revision
// footer, never bytes.

import { marked } from "marked";
import definitions from "../../tools.definitions.json";

export function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&#34;")
    .replace(/'/g, "&#39;");
}

export function renderPage(path: string, markdown: string, revID: string, version: number): string {
  const body = marked.parse(markdown, { async: false }) as string;
  return (
    `<!doctype html><title>${escapeHtml(path)} — MintWiki</title>` +
    `<article>${body}</article>` +
    `<footer><small>revision ${revID} · version ${version}</small></footer>` +
    `<script src="/webmcp.js" defer></script>`
  );
}

export function renderIndex(paths: string[]): string {
  let out = "<!doctype html><title>MintWiki</title><h1>MintWiki</h1><ul>";
  for (const p of paths) out += `<li><a href="/${escapeHtml(p)}">${escapeHtml(p)}</a></li>`;
  out += '</ul><script src="/webmcp.js" defer></script>';
  return out;
}

// webmcpJS mirrors site.WebMCPJS (Go) statement for statement: the
// script is defensive (no WebMCP host = no-op), registers every tool
// from the shared definitions, and its execute() posts a tools/call
// JSON-RPC request to the wiki's own /mcp endpoint, keeping exactly
// one server-side execution path. For propose_edit it forwards a
// bearer token from localStorage["mintwiki_token"] when present.
export function webmcpJS(): string {
  return (
    "// Generated by mintwiki from the shared tool definitions (tools.definitions.json).\n" +
    "// Do not edit by hand — regenerated whenever a page head moves.\n" +
    "(function () {\n" +
    "  var TOOLS = " +
    JSON.stringify(definitions) +
    ";\n" +
    `  var mc = (typeof navigator !== "undefined" && navigator.modelContext) ||
           (typeof document !== "undefined" && document.modelContext);
  if (!mc || typeof mc.registerTool !== "function") return;
  function callTool(name, args) {
    var headers = { "Content-Type": "application/json" };
    try {
      var tok = window.localStorage.getItem("mintwiki_token");
      if (tok) headers["Authorization"] = "Bearer " + tok;
    } catch (e) { /* storage unavailable: read tools still work */ }
    return fetch("/mcp", {
      method: "POST",
      headers: headers,
      body: JSON.stringify({ jsonrpc: "2.0", id: Date.now(), method: "tools/call",
                             params: { name: name, arguments: args || {} } })
    }).then(function (r) { return r.json(); }).then(function (msg) {
      if (msg.error) throw new Error(msg.error.message || "MCP error");
      var res = msg.result || {};
      var text = (res.content && res.content[0] && res.content[0].text) || "{}";
      var parsed;
      try { parsed = JSON.parse(text); } catch (e) { parsed = text; }
      if (res.isError) throw new Error(typeof parsed === "string" ? parsed : (parsed.error || text));
      return parsed;
    });
  }
  TOOLS.forEach(function (t) {
    try {
      mc.registerTool({
        name: t.name,
        description: t.description,
        inputSchema: t.inputSchema,
        execute: function (args) { return callTool(t.name, args); }
      });
    } catch (e) { /* a host rejecting one tool must not break the rest */ }
  });
})();
`
  );
}
