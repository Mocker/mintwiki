// Package site statically builds the wiki into plain HTML files: one
// index plus one .html per page, rendered from each page's head revision.
// Viewing MintWiki is reading static files — the build is regenerated
// whenever a head moves, and the whole site directory can be served by
// any static file server, not just MintWiki's own.
package site

import (
	"bytes"
	"fmt"
	"html"
	"os"
	"path/filepath"
	"strings"

	"github.com/yuin/goldmark"

	"github.com/Mocker/mintwiki/internal/store"
	"github.com/Mocker/mintwiki/internal/tools"
)

// Build renders every page in the store into outDir. Files are written
// atomically (temp + rename) so a concurrent reader never sees a partial
// page. Returns the number of pages built.
func Build(st *store.Store, outDir string) (int, error) {
	pages, err := st.ListPages()
	if err != nil {
		return 0, err
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return 0, err
	}
	for _, path := range pages {
		page, err := st.GetPage(path)
		if err != nil {
			return 0, err
		}
		var buf bytes.Buffer
		if err := goldmark.Convert(page.Content, &buf); err != nil {
			return 0, err
		}
		doc := fmt.Sprintf("<!doctype html><title>%s — MintWiki</title><article>%s</article><footer><small>revision %s · version %d</small></footer><script src=\"/webmcp.js\" defer></script>",
			html.EscapeString(path), buf.String(), page.RevID, page.Version)
		target := filepath.Join(outDir, filepath.FromSlash(path)+".html")
		if err := writeAtomic(target, []byte(doc)); err != nil {
			return 0, err
		}
	}
	var idx strings.Builder
	idx.WriteString("<!doctype html><title>MintWiki</title><h1>MintWiki</h1><ul>")
	for _, p := range pages {
		fmt.Fprintf(&idx, `<li><a href="/%s">%s</a></li>`, html.EscapeString(p), html.EscapeString(p))
	}
	idx.WriteString("</ul><script src=\"/webmcp.js\" defer></script>")
	if err := writeAtomic(filepath.Join(outDir, "index.html"), []byte(idx.String())); err != nil {
		return 0, err
	}
	js, err := WebMCPJS()
	if err != nil {
		return 0, err
	}
	if err := writeAtomic(filepath.Join(outDir, "webmcp.js"), js); err != nil {
		return 0, err
	}
	return len(pages), nil
}

// WebMCPJS generates the WebMCP registration script from the shared tool
// definitions — the same definitions the HTTP MCP server serves, so the
// browser and non-browser agent surfaces can never drift. The script is
// defensive: with no WebMCP host present (an ordinary browser) it does
// nothing. Its execute() posts a tools/call JSON-RPC request to the
// wiki's own /mcp endpoint, keeping exactly one server-side execution
// path. For propose_edit it forwards a bearer token from
// localStorage["mintwiki_token"] when the browser user has stored one;
// read tools need no token.
func WebMCPJS() ([]byte, error) {
	defs, err := tools.DefinitionJSON()
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Generated by mintwiki from the shared tool definitions (internal/tools).\n")
	b.WriteString("// Do not edit by hand — regenerate with `mintwiki build`.\n")
	b.WriteString("(function () {\n")
	b.WriteString("  var TOOLS = ")
	b.Write(defs)
	b.WriteString(";\n")
	b.WriteString(`  var mc = (typeof navigator !== "undefined" && navigator.modelContext) ||
           (typeof document !== "undefined" && document.modelContext);
  if (!mc || typeof mc.registerTool !== "function") return;
  function callTool(name, args) {
    var headers = { "Content-Type": "application/json" };
    try {
      var tok = window.localStorage.getItem("mintwiki_token");
      if (tok) headers["Authorization"] = "Bearer " + tok;
    } catch (e) { /* storage unavailable: read tools still work */ }
    return fetch("/mcp", {
      method: "POST",
      headers: headers,
      body: JSON.stringify({ jsonrpc: "2.0", id: Date.now(), method: "tools/call",
                             params: { name: name, arguments: args || {} } })
    }).then(function (r) { return r.json(); }).then(function (msg) {
      if (msg.error) throw new Error(msg.error.message || "MCP error");
      var res = msg.result || {};
      var text = (res.content && res.content[0] && res.content[0].text) || "{}";
      var parsed;
      try { parsed = JSON.parse(text); } catch (e) { parsed = text; }
      if (res.isError) throw new Error(typeof parsed === "string" ? parsed : (parsed.error || text));
      return parsed;
    });
  }
  TOOLS.forEach(function (t) {
    try {
      mc.registerTool({
        name: t.name,
        description: t.description,
        inputSchema: t.inputSchema,
        execute: function (args) { return callTool(t.name, args); }
      });
    } catch (e) { /* a host rejecting one tool must not break the rest */ }
  });
})();
`)
	return []byte(b.String()), nil
}

func writeAtomic(target string, content []byte) error {
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	tmp := target + ".tmp"
	if err := os.WriteFile(tmp, content, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, target)
}
